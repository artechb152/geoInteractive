// Web delivery for the Blender top-down map of „זיהוי סוגי תכסית בשטח” (render_land_cover.py).
// The passes are framed 1:1 on LandCoverMap's 400 × 250 map tile. The bare ground ships
// full-frame and opaque; every region pass and cast shadow is cropped to its own alpha box,
// so its <image> covers only that region, and the placement (in map units) is written to
// landCoverRenders.data.ts. Never resize the renders.
// Shadow-catcher passes also carry faint light (white, low alpha); only the darkening is
// kept: black at alpha·(1 − luminance).
const fs = require('node:fs');
const path = require('node:path');
const sharp = require(require.resolve('sharp', { paths: [path.dirname(require.resolve('next/package.json'))] }));

const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'qa-output/land-cover-blender');
const out = path.join(root, 'public/assets/lessons/topic02/land-cover');
const dataFile = path.join(root, 'src/components/lessons/topic-02/landCoverRenders.data.ts');
const MAP_W = 400;
const SEASONAL = ['grove', 'garrigue', 'batha', 'terraces', 'fields'];
const REGIONS = ['grove', 'garrigue', 'batha', 'planted', 'terraces', 'fields', 'village', 'orchard', 'reservoir', 'track', 'road', 'power', 'fence'];
const RAISED = ['grove', 'garrigue', 'planted', 'village', 'orchard', 'reservoir', 'power', 'fence'];
const FULL = ['ground-winter'];
const LAYERS = REGIONS.flatMap((k) => (SEASONAL.includes(k) ? [`${k}-winter`] : [k]));
const SHADOW = RAISED.map((k) => 'shadow-' + k);
const PAD = 3; // px of transparent margin kept around a cropped layer

fs.mkdirSync(out, { recursive: true });

async function alphaBox(buf, width, height) {
  const { data } = await sharp(buf).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = width, y0 = height, x1 = -1, y1 = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (data[(y * width + x) * 4 + 3] > 2) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  if (x1 < 0) return null;
  x0 = Math.max(0, x0 - PAD); y0 = Math.max(0, y0 - PAD);
  x1 = Math.min(width - 1, x1 + PAD); y1 = Math.min(height - 1, y1 + PAD);
  return { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };
}

(async () => {
  const placed = {};
  let px = null;
  let total = 0;
  for (const name of [...FULL, ...SHADOW, ...LAYERS]) {
    let src = path.join(source, name + '.png');
    const { width, height } = await sharp(src).metadata();
    px = px ?? width / MAP_W;
    if (Math.abs(width / MAP_W - px) > 1e-6) throw new Error(`${name}: ${width} px wide, expected ${MAP_W * px}`);
    if (SHADOW.includes(name)) {
      const { data } = await sharp(src).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      const lin = (v) => ((v / 255) <= 0.04045 ? v / 255 / 12.92 : ((v / 255 + 0.055) / 1.055) ** 2.4);
      for (let i = 0; i < data.length; i += 4) {
        const lum = 0.2126 * lin(data[i]) + 0.7152 * lin(data[i + 1]) + 0.0722 * lin(data[i + 2]);
        const a = Math.round(data[i + 3] * Math.max(0, 1 - lum));
        data[i] = data[i + 1] = data[i + 2] = 0;
        data[i + 3] = a < 12 ? 0 : a; // drops the catcher's stray noise far from the object
      }
      src = await sharp(data, { raw: { width, height, channels: 4 } }).png().toBuffer();
    }
    let box = { left: 0, top: 0, width, height };
    if (!FULL.includes(name)) {
      box = await alphaBox(src, width, height);
      if (!box) throw new Error(`${name}: empty render`);
    }
    const file = path.join(out, name + '.webp');
    const img = sharp(src).extract(box);
    if (FULL.includes(name)) await img.removeAlpha().webp({ quality: 80, effort: 6 }).toFile(file);
    else await img.webp({ quality: SHADOW.includes(name) ? 70 : 82, alphaQuality: 90, effort: 6 }).toFile(file);
    const r = (v) => Math.round((v / px) * 1000) / 1000;
    placed[name] = { file: name + '.webp', x: r(box.left), y: r(box.top), w: r(box.width), h: r(box.height) };
    const kb = fs.statSync(file).size / 1024;
    total += kb;
    console.log(name.padEnd(18), `${box.width}×${box.height}`, Math.round(kb) + ' KB');
  }
  console.log('total', Math.round(total) + ' KB');
  const body = Object.entries(placed)
    .map(([k, v]) => `  '${k}': { file: '${v.file}', x: ${v.x}, y: ${v.y}, w: ${v.w}, h: ${v.h} },`)
    .join('\n');
  fs.writeFileSync(
    dataFile,
    `/**
 * Generated by scripts/blender/package_land_cover.cjs — do not edit by hand.
 * Placement of each rendered layer of LandCoverMap on its 400 × 250 map tile
 * (x, y, w, h in map units; renders at ${px} px per unit, see render_land_cover.py).
 */
export type LandCoverRender = { file: string; x: number; y: number; w: number; h: number };

export const LAND_COVER_RENDERS = {
${body}
} as const satisfies Record<string, LandCoverRender>;
`,
  );
  console.log('wrote', path.relative(root, dataFile));
})();
