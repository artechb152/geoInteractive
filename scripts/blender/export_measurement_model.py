"""Measurement mission — the live 3-D model's assets, exported from the same fields as the renders.

Topic-02 #scene-coordinates → "אליפסואיד, גיאואיד וגליות". The page turns the landscape in
WebGL (MeasurementLandscape3D.tsx). It is built from exactly what render_measurement_landscape.py
renders, so the turnable model and the layered renders (its no-WebGL fallback) are one landscape:

    model-height.bin    the ground H (m) on a 10 m grid — every 2nd node of the render's 5 m
                        field, the stations' local corrections included. Int16, decimetres,
                        row-major from the front-left corner (x → the sea, y → away).
    model-albedo.png    the diorama seen straight down (orthographic, the renders' sun, sky and
                        AgX look): ground, rock, fields, trees with their shadows, beach and
                        sea. Light on diffuse ground does not depend on where it is seen from,
                        so the page drapes this image on the height grid and shows it unlit;
                        package_measurement_landscape.cjs makes the WebP.
    measurementModel.data.ts  grid size, file names, and the points the page's camera frames
                        (the closed model's base corners and top edges — the same points the
                        renders' camera was solved on).

    & 'C:/Program Files/Blender Foundation/Blender 5.2/blender.exe' --background \
        --python scripts/blender/export_measurement_model.py
    node scripts/blender/package_measurement_landscape.cjs

ML_SAMPLES=0.25 renders a quick draft of the texture. No network.
"""
import bpy, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import render_measurement_landscape as R  # noqa: E402  (fields, materials, geometry; its main() does not run)

PUB = os.path.join(R.ROOT, 'public/reference-assets/measurement-mission')
MODEL_TS = os.path.join(R.ROOT, 'src/components/lessons/topic-02/measurementModel.data.ts')
STEP = 2                     # every 2nd node of the 5 m field → the 10 m grid the page meshes
TEX_W, TEX_H = 2250, 1150    # 2 m per texel; the footprint's own proportions (4500 × 2300 m)


def main():
    F = R.build_fields()
    Mk = R.masks(F)
    sc = R.setup()
    coll = sc.collection
    mats = dict(ground=R.ground_material(), trees=R.tree_material(), water=R.water_material(),
                cut=R.cut_material('Cut'), water_cut=R.water_cut_material())
    full = R.build_diorama(F, Mk, mats, -R.D_M / 2, coll, 'full')
    for w in full['walls']:
        w.hide_render = True                       # upright faces have no area from above
    T = R.place_trees(F, Mk)
    R.tree_mesh('Trees', T, np.ones(len(T['x']), bool), mats, coll)

    # the diorama straight down: x to the right, y up the image (away from the viewer)
    cd = bpy.data.cameras.new('Top')
    cd.type = 'ORTHO'
    cd.sensor_fit = 'HORIZONTAL'
    cd.ortho_scale = R.W_M / R.MPU
    cd.clip_start, cd.clip_end = .1, 40
    cam = bpy.data.objects.new('Top', cd)
    coll.objects.link(cam)
    sc.camera = cam
    cam.location = (0, 0, 20)
    cam.rotation_euler = (0, 0, 0)
    sc.render.resolution_x, sc.render.resolution_y = TEX_W, TEX_H
    R.look(sc, True)
    sc.cycles.samples = max(16, int(256 * R.SAMPLE_SCALE))
    sc.render.filepath = os.path.join(R.OUT, 'model-albedo.png')
    bpy.ops.render.render(write_still=True)
    print('rendered model-albedo')

    # heights
    H = F['H'][::STEP, ::STEP]
    assert H.shape == (int(R.D_M / (R.CELL * STEP)) + 1, int(R.W_M / (R.CELL * STEP)) + 1), H.shape
    os.makedirs(PUB, exist_ok=True)
    np.round(H * 10).astype('<i2').tofile(os.path.join(PUB, 'model-height.bin'))
    for sid, s in R.ST.items():
        got = R.sample_grid(F['H'], s['x'], s['y'])
        print(f"station {sid}: H on the 5 m field {got:.2f} m (wants {s['H']})")

    # the points the camera frames: the same set render_measurement_landscape.camera() was solved on
    top = np.maximum(F['H'] * R.KZ + F['N'] * R.KN, F['N'] * R.KN)
    z_base = full['z_base']
    target_z = float((F['H'] * R.KZ + F['N'] * R.KN).max()) * .35   # where the renders' camera solve started
    fit = [(x / R.MPU, y / R.MPU, z_base) for x in (-R.W_M / 2, R.W_M / 2) for y in (-R.D_M / 2, R.D_M / 2)]
    for x in np.linspace(-R.W_M / 2, R.W_M / 2, 31):
        for y in (-R.D_M / 2, R.D_M / 2):
            fit.append((x / R.MPU, y / R.MPU, float(R.sample_grid(top, x, y))))
    for y in np.linspace(-R.D_M / 2, R.D_M / 2, 17):
        for x in (-R.W_M / 2, R.W_M / 2):
            fit.append((x / R.MPU, y / R.MPU, float(R.sample_grid(top, x, y))))
    pts = ',\n    '.join('[' + ', '.join(f'{v:.4f}' for v in p) + ']' for p in fit)
    ts = f'''// AUTO-GENERATED by scripts/blender/export_measurement_model.py — do not edit by hand.
// The live 3-D landscape (MeasurementLandscape3D.tsx): the same ground as the renders in
// public/reference-assets/measurement-mission/, as a height grid and a top-down image.

export const MEASUREMENT_MODEL = {{
  /** Ground H (m) every {R.CELL * STEP:g} m: Int16 decimetres, row-major, row 0 = the front edge (y = −{R.D_M / 2:g} m), column 0 = the left edge (x = −{R.W_M / 2:g} m). */
  heights: {{ file: 'model-height.bin', cols: {H.shape[1]}, rows: {H.shape[0]}, cell: {R.CELL * STEP:g}, metresPerUnit: 0.1 }},
  /** The diorama seen straight down, covering the footprint exactly (image top = the back edge). */
  albedo: {{ file: 'model-albedo.webp', w: {TEX_W}, h: {TEX_H} }},
  /** Bottom of the model's base (world units). */
  baseZ: {z_base:.5f},
  /** Height (world units) of the point the camera turns about: the renders' camera solve started there. */
  targetZ: {target_z:.5f},
  /** The closed model's base corners and top edges (world units): what the camera keeps in frame. */
  fit: [
    {pts},
  ] as const,
}} as const;
'''
    open(MODEL_TS, 'w', encoding='utf-8', newline='\n').write(ts)
    print('wrote', MODEL_TS)


main()
