// Web delivery for the Blender side view of „תצורות הצומח וגובהן” (render_vegetation_ladder.py).
// The passes are framed 1:1 on VegetationLadder's 500 × 206 viewBox. Every pass is cropped
// to its own alpha box, so its <image> covers only that formation (or slab, or shadow), and
// the placement (in viewBox units) is written to vegetationLadderRenders.data.ts. Never
// resize the renders.
// Shadow-catcher passes also carry faint light (white, low alpha); only the darkening is
// kept: black at alpha·(1 − luminance), and stray catcher noise (alpha < 12) is dropped.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require(require.resolve('sharp', { paths: [path.dirname(require.resolve('next/package.json'))] }));

const root = path.resolve(__dirname, '../..');
const source = path.join(root, 'qa-output/vegetation-ladder-blender');
const out = path.join(root, 'public/assets/lessons/topic02/vegetation-ladder');
const dataFile = path.join(root, 'src/components/lessons/topic-02/vegetationLadderRenders.data.ts');
const VB_W = 500;
const FORMATIONS = ['herbaceous', 'batha', 'garrigue', 'grove', 'planted'];
const SHADOW = FORMATIONS.map((k) => 'shadow-' + k);
const PAD = 3; // px of transparent margin kept around a cropped layer

fs.mkdirSync(out, { recursive: true });

(async () => {
  const placed = {};
  let px = null;
  let total = 0;
  for (const name of ['land', ...SHADOW, ...FORMATIONS]) {
    let src = path.join(source, name + '.png');
    const { width, height } = await sharp(src).metadata();
    px = px ?? width / VB_W;
    if (Math.abs(width / VB_W - px) > 1e-6) throw new Error(`${name}: ${width} px wide, expected ${VB_W * px}`);
    const { data } = await sharp(src).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    if (SHADOW.includes(name)) {
      const lin = (v) => ((v / 255) <= 0.04045 ? v / 255 / 12.92 : ((v / 255 + 0.055) / 1.055) ** 2.4);
      for (let i = 0; i < data.length; i += 4) {
        const lum = 0.2126 * lin(data[i]) + 0.7152 * lin(data[i + 1]) + 0.0722 * lin(data[i + 2]);
        const a = Math.round(data[i + 3] * Math.max(0, 1 - lum));
        data[i] = data[i + 1] = data[i + 2] = 0;
        data[i + 3] = a < 12 ? 0 : a;
      }
      src = await sharp(data, { raw: { width, height, channels: 4 } }).png().toBuffer();
    }
    let x0 = width, y0 = height, x1 = -1, y1 = -1;
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        if (data[(y * width + x) * 4 + 3] > 2) {
          if (x < x0) x0 = x;
          if (x > x1) x1 = x;
          if (y < y0) y0 = y;
          if (y > y1) y1 = y;
        }
      }
    }
    if (x1 < 0) throw new Error(`${name}: empty render`);
    x0 = Math.max(0, x0 - PAD); y0 = Math.max(0, y0 - PAD);
    x1 = Math.min(width - 1, x1 + PAD); y1 = Math.min(height - 1, y1 + PAD);
    const box = { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };
    const file = path.join(out, name + '.webp');
    await sharp(src).extract(box).webp({ quality: SHADOW.includes(name) ? 70 : 84, alphaQuality: 90, effort: 6 }).toFile(file);
    const r = (v) => Math.round((v / px) * 1000) / 1000;
    placed[name] = { file: name + '.webp', x: r(box.left), y: r(box.top), w: r(box.width), h: r(box.height) };
    const kb = fs.statSync(file).size / 1024;
    total += kb;
    console.log(name.padEnd(18), `${box.width}×${box.height}`, Math.round(kb) + ' KB');
  }
  console.log('total', Math.round(total) + ' KB');
  const body = Object.entries(placed)
    .map(([k, v]) => `  '${k}': { file: '${v.file}', x: ${v.x}, y: ${v.y}, w: ${v.w}, h: ${v.h} },`)
    .join('\n');
  fs.writeFileSync(
    dataFile,
    `/**
 * Generated by scripts/blender/package_vegetation_ladder.cjs — do not edit by hand.
 * Placement of each rendered layer of VegetationLadder in its 500 × 206 viewBox
 * (x, y, w, h in viewBox units; renders at ${px} px per unit, see render_vegetation_ladder.py).
 */
export type VegetationLadderRender = { file: string; x: number; y: number; w: number; h: number };

export const VEGETATION_LADDER_RENDERS = {
${body}
} as const satisfies Record<string, VegetationLadderRender>;
`,
  );
  console.log('wrote', path.relative(root, dataFile));
})();
